function normalize(value: string): string {
  return value
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}

const NORMALIZED_INDEX: Record<string, string> = {};
for (const [name, url] of Object.entries(CONSULTA_URLS)) {
  NORMALIZED_INDEX[normalize(name)] = url;
}

/**
 * URL oficial para consultar el estatus de líneas de un operador.
 * Intenta coincidencia exacta, luego normalizada y por subcadena.
 */
export function getConsultaUrl(operator: string): string | null {
  if (CONSULTA_URLS[operator]) return CONSULTA_URLS[operator];
  const n = normalize(operator);
  if (!n) return null;
  if (NORMALIZED_INDEX[n]) return NORMALIZED_INDEX[n];
  for (const key of Object.keys(NORMALIZED_INDEX)) {
    if (n.includes(key) || key.includes(n)) return NORMALIZED_INDEX[key];
  }
  return null;
}
